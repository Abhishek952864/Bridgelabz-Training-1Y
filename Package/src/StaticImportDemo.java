import static java.lang.Math.*;

public class StaticImportDemo {

    public static void main(String[] args) {

        System.out.println("Square Root of 25: " + sqrt(25));
        System.out.println("2 power 3: " + pow(2,3));
        System.out.println("Max value: " + max(10,20));
        System.out.println("Min value: " + min(10,20));
        System.out.println("Absolute value: " + abs(-15));

    }

}